import { randomUUID } from 'node:crypto';
import type { AdminMeetingType, Booking, CreateMeetingTypeRequest } from '@app/api/types';
import { ApiError } from './errors.js';

type MeetingTypeStore = {
  create: (data: CreateMeetingTypeRequest) => AdminMeetingType;
  list: () => AdminMeetingType[];
  // Throws the contract 404 for an unknown id: the shared tail of every route
  // that fetches a meeting type by id.
  getByIdOrThrow: (id: string) => AdminMeetingType;
};

type BookingStore = {
  // Bookings of every meeting type: slot availability is checked against all
  // of them (ADR 0002), and the owner's list (#15) shows them all.
  list: () => Booking[];
  create: (data: Omit<Booking, 'id'>) => Booking;
};

export type Storage = {
  meetingTypes: MeetingTypeStore;
  bookings: BookingStore;
};

// In-memory storage living on the app instance: created inside `buildApp()`,
// never as a module singleton, so test runs stay isolated (docs/test-plan.md).
export function createStorage(): Storage {
  const meetingTypes = new Map<string, AdminMeetingType>();
  const bookings = new Map<string, Booking>();

  return {
    meetingTypes: {
      create: (data) => {
        // Ids are UUIDs generated by the server (spec #10).
        const meetingType: AdminMeetingType = { id: randomUUID(), ...data };
        meetingTypes.set(meetingType.id, meetingType);
        return meetingType;
      },
      list: () => [...meetingTypes.values()],
      getByIdOrThrow: (id) => {
        const meetingType = meetingTypes.get(id);
        if (!meetingType) {
          throw new ApiError(404, 'meeting_type_not_found', 'Тип встречи не найден.');
        }
        return meetingType;
      },
    },
    bookings: {
      create: (data) => {
        const booking: Booking = { id: randomUUID(), ...data };
        bookings.set(booking.id, booking);
        return booking;
      },
      // Sorted by `start` asc: the owner sees the nearest booking first
      // (user story 9), whatever the insertion order was.
      list: () => [...bookings.values()].sort((a, b) => Date.parse(a.start) - Date.parse(b.start)),
    },
  };
}

// Options every route module receives from `buildApp()`: the per-app storage
// and the injected clock (ADR 0002) — the routes differ only in which parts
// they use, so the bundle is declared once.
export type RouteOptions = {
  storage: Storage;
  // Injected clock (ADR 0002): «сегодня» and «предстоящие брони» are judged
  // against it, not a direct clock read in the domain logic.
  now: () => string;
};
